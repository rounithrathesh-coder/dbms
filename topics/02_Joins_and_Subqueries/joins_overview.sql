-- DBMS Topic 02: Relational Joins Reference

-- Visualizing Relational Joins:
-- 1. INNER JOIN: Returns records with matching values in both tables.
-- 2. LEFT JOIN: Returns all records from left table, and matched from right.
-- 3. RIGHT JOIN: Returns all records from right table, and matched from left.
-- 4. FULL OUTER JOIN: Returns all records when there is a match in either.
-- 5. CROSS JOIN: Cartesian product of all rows.
-- 6. SELF JOIN: Regular join where table is joined with itself.
